# Nama variabel ditambah 4 digit nim terakhir contoh: ipk_2002
# Program ini menggunakan fungsi input()
# program konversi nilai angka menjadi huruf

nilai_2002 = int(input("Inputkan nilai angka= "))

if nilai_2002 >= 81:
    print("A")
elif nilai_2002 >= 70:
    print("B")
elif nilai_2002 >= 60:
    print("C")
elif nilai_2002 >= 50:
    print("D")
else:
    print("E")